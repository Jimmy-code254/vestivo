import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { FileText, Download } from "lucide-react";
import { Button } from "@/components/ui/button";

type Transaction = {
  id: string;
  type: string;
  amount: number;
  description: string | null;
  reference: string | null;
  created_at: string;
};

interface StatementExportProps {
  transactions: Transaction[];
  userName: string;
  walletBalance: number;
  period?: string; // e.g. "October 2026"
}

const CREDIT_TYPES = ["deposit", "payout", "loan_disbursement"];

function formatDate(dateStr: string) {
  return new Date(dateStr).toLocaleDateString("en-KE", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}

function signedAmount(tx: Transaction): number {
  const isCredit = CREDIT_TYPES.includes(tx.type);
  return isCredit ? Number(tx.amount) : -Number(tx.amount);
}

export default function StatementExport({
  transactions,
  userName,
  walletBalance,
  period,
}: StatementExportProps) {
  const handleExportPDF = () => {
    const doc = new jsPDF({ orientation: "portrait", unit: "pt", format: "a4" });
    const pageWidth = doc.internal.pageSize.getWidth();
    const generatedDate = new Date().toLocaleDateString("en-KE", {
      day: "numeric",
      month: "long",
      year: "numeric",
    });

    // ── Header ──────────────────────────────────────────────────────────────
    doc.setFontSize(20);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(30, 30, 30);
    doc.text("VESTIVO — Account Statement", pageWidth / 2, 50, { align: "center" });

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(90, 90, 90);
    const meta = [
      `Account Holder : ${userName}`,
      `Balance        : KES ${walletBalance.toLocaleString(undefined, { minimumFractionDigits: 2 })}`,
      period ? `Period         : ${period}` : null,
      `Generated      : ${generatedDate}`,
    ].filter(Boolean) as string[];
    meta.forEach((line, i) => doc.text(line, 40, 75 + i * 16));

    // ── Table ────────────────────────────────────────────────────────────────
    const rows = transactions.map((tx) => [
      formatDate(tx.created_at),
      tx.type.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
      tx.description || "—",
      tx.reference || "—",
      `KES ${signedAmount(tx).toLocaleString(undefined, { minimumFractionDigits: 2 })}`,
    ]);

    autoTable(doc, {
      head: [["Date", "Type", "Description", "Reference", "Amount (KES)"]],
      body: rows,
      startY: 75 + meta.length * 16 + 16,
      styles: { fontSize: 9, cellPadding: 5 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      alternateRowStyles: { fillColor: [246, 246, 252] },
      columnStyles: {
        0: { cellWidth: 75 },
        1: { cellWidth: 90 },
        2: { cellWidth: 160 },
        3: { cellWidth: 100 },
        4: { cellWidth: 80, halign: "right" },
      },
      didDrawCell: (data) => {
        // Colour the amount column: positive = green, negative = red
        if (data.section === "body" && data.column.index === 4) {
          const val = parseFloat(
            (data.cell.text[0] || "").replace(/[^0-9.-]/g, "")
          );
          if (!isNaN(val)) {
            data.cell.styles.textColor = val < 0 ? [220, 38, 38] : [22, 163, 74];
          }
        }
      },
    });

    // ── Footer ───────────────────────────────────────────────────────────────
    const pageHeight = doc.internal.pageSize.getHeight();
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text("Generated by Vestivo", pageWidth / 2, pageHeight - 20, { align: "center" });

    const filename = `vestivo-statement-${period ? period.replace(/\s+/g, "-").toLowerCase() : Date.now()}.pdf`;
    doc.save(filename);
  };

  const handleExportCSV = () => {
    const headers = "Date,Type,Description,Reference,Amount";
    const rows = transactions.map((tx) => {
      const date = formatDate(tx.created_at);
      const type = tx.type.replace(/_/g, " ");
      const desc = (tx.description || "").replace(/,/g, " ");
      const ref = (tx.reference || "").replace(/,/g, " ");
      const amount = signedAmount(tx).toFixed(2);
      return `${date},${type},${desc},${ref},${amount}`;
    });

    const csv = [headers, ...rows].join("\n");
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute(
      "download",
      `vestivo-statement-${period ? period.replace(/\s+/g, "-").toLowerCase() : Date.now()}.csv`
    );
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex items-center gap-2">
      <Button variant="outline" size="sm" onClick={handleExportPDF} className="gap-1.5">
        <FileText className="w-4 h-4" />
        Export PDF
      </Button>
      <Button variant="outline" size="sm" onClick={handleExportCSV} className="gap-1.5">
        <Download className="w-4 h-4" />
        Export CSV
      </Button>
    </div>
  );
}
